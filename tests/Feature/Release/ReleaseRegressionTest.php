function lockedScenario(): WorkflowScenario
{
    $scenario = new WorkflowScenario;
    $scenario->approveEverything();
    $scenario->advance(PeriodStatus::Finalized);
    $scenario->advance(PeriodStatus::Locked);

    return $scenario;
}

/**
 * @param  list<array<string, string|null>>  $rows  report rows keyed by heading
 */
function scoreOf(array $rows, string $subject): string
{
    foreach ($rows as $row) {
        if (in_array($subject, $row, true)) {
            return (string) $row['Skor berlaku'];
        }
    }

    throw new RuntimeException("Subject {$subject} is not in the report.");
}

test('a locked period refuses direct edits of actuals and targets and keeps every version', function (): void {
    $scenario = lockedScenario();
    $hr = $scenario->hr();
    $target = $scenario->scorecards->target('SC-QUALITY', 'W-001');
    $actualVersions = KpiActualVersion::query()->count();
    $targetVersions = PeriodTargetVersion::query()->count();

    $editActual = fn () => app(ActualService::class)->saveDrafts(WorkflowScenario::actor($hr), $scenario->period->id, ActualAccess::everything(), [new ActualEntry(
        reference: $target->public_id,
        targetId: $target->id,
        windowStart: PeriodFixtures::STARTS_ON,
        windowEnd: PeriodFixtures::ENDS_ON,
        value: '10',
        unit: (string) $target->definitionVersion->unit,
        note: null,
    )]);
    $editTarget = fn () => app(TargetService::class)->saveDrafts(WorkflowScenario::actor($hr), $scenario->period->id, PeriodFixtures::everything(), [$scenario->scorecards->fixtures->entry($target, '50')], 'Ubah setelah lock', true);

    expect(AccessFixtures::violatedRule($editActual))->toBe('period_not_accepting_actuals')
        ->and(AccessFixtures::violatedRule($editTarget))->toBe('period_not_accepting_targets')
        ->and(AccessFixtures::violatedRule(fn () => $scenario->scorecards->calculate()))->toBe('scorecard_final')
        ->and(KpiActualVersion::query()->count())->toBe($actualVersions)
        ->and(PeriodTargetVersion::query()->count())->toBe($targetVersions)
        ->and($scenario->period->refresh()->status)->toBe(PeriodStatus::Locked);
});

test('submitting the same drafts twice submits them once', function (): void {
    $scenarios = new ScorecardScenario;
    $scenarios->enter($scenarios->target('SC-QUALITY', 'W-001'), '95.5');
    $actuals = app(ActualService::class);

    $actuals->submit($scenarios->hrActor(), $scenarios->period->id, ActualAccess::everything());
    $versions = KpiActualVersion::query()->count();

    expect(AccessFixtures::violatedRule(fn () => $actuals->submit($scenarios->hrActor(), $scenarios->period->id, ActualAccess::everything())))->toBe('nothing_to_submit')
        ->and(KpiActualVersion::query()->count())->toBe($versions)
        ->and(KpiActualVersion::query()->where('status', 'submitted')->count())->toBe(1);
});

test('an export made before a correction keeps its file; one requested or generated after shows the corrected score', function (): void {
    $scenario = lockedScenario();
    $hr = $scenario->hr();
    $exports = app(ExportService::class);
    $filters = ['period' => $scenario->period->public_id];

    $before = $exports->request(WorkflowScenario::actor($hr), $hr, 'scorecards', 'xlsx', $filters)->refresh();
    $beforeChecksum = $before->checksum_sha256;
    $beforeScore = scoreOf(ReportHarness::rows($hr, 'scorecards', $filters), 'W-001');

    // Queued before the correction, generated by the worker after it.
    Queue::fake();
    $queued = $exports->request(WorkflowScenario::actor($hr), $hr, 'scorecards', 'xlsx', [...$filters, 'level' => 'employee'])->refresh();
    expect($queued->status)->toBe(ExportStatus::Queued);

    $corrections = app(CorrectionService::class);
    $request = $corrections->request(WorkflowScenario::actor($hr), $hr, $scenario->actual('SC-QUALITY', 'W-001')->id, '50', null, 'Salah input laporan mutu', 'BA-TEST-019');
    $corrections->approve(WorkflowScenario::actor($scenario->management), $scenario->management, $request->id, $request->lock_version, 'Disetujui');

    $afterScore = scoreOf(ReportHarness::rows($hr, 'scorecards', $filters), 'W-001');
    expect($afterScore)->not->toBe($beforeScore);

    // The earlier file is immutable: same bytes, same checksum.
    expect($before->refresh()->checksum_sha256)->toBe($beforeChecksum)
        ->and(hash('sha256', Storage::disk('s3')->get((string) $before->path)))->toBe($beforeChecksum);

    // The queued export reads the data when the worker runs: the corrected score.
    $exports->generate($queued->id);
    $queuedRows = ReportHarness::workbook($queued->refresh())['rows'];
    $header = ReportHarness::workbook($queued)['header'];
    $scoreColumn = array_search('Skor berlaku', $header, true);
    $row = collect($queuedRows)->first(fn (array $cells): bool => in_array('W-001', $cells, true));
    expect($queued->status)->toBe(ExportStatus::Completed)
        ->and($row[$scoreColumn])->toBe($afterScore);

    // A new request after the correction is a new export, not the old file.
    $after = $exports->request(WorkflowScenario::actor($hr), $hr, 'scorecards', 'xlsx', $filters)->refresh();
    expect($after->id)->not->toBe($before->id);
});
